import Foundation

/// The key directory and file names the identity core and its CLI agree
/// on. This slice has no install step or root-owned configuration file
/// (that is slice 3's, which wires the real deployed path); the default
/// here exists so `individuator`'s subcommands have something concrete to
/// operate on in the meantime, and a caller overrides it with `--key-dir`.
public enum IndividuatorPaths {
    public static let defaultKeyDirectory = URL(fileURLWithPath: "/var/db/individuator")
    public static let keyFileName = "machine.key"
    public static let certificateFileName = "machine-cert.pem"

    /// The root-owned configuration `IndividuatorRootConfig` reads (CQ·447
    /// slice 3): the Bosun host name and address, the Library root CA path,
    /// and the operator uid the root daemon's Unix socket accepts a
    /// `register` request from. Installed by `bin/install-individuator`,
    /// never generated by this package itself.
    public static let defaultRootConfigPath = URL(fileURLWithPath: "/etc/individuator/config.json")

    /// The Unix socket the root daemon listens on for the one `register`
    /// operation (CQ·447 slice 3). Deliberately a sibling of
    /// `defaultKeyDirectory`, not inside it: that directory is `0700`
    /// (root-only), which would stop the non-root operator CLI from ever
    /// reaching a socket placed inside it, while this directory is `0755`
    /// so any local uid can traverse it to reach the socket — the real
    /// access control is the peer-uid check at `accept()` time, not this
    /// directory's mode. `/var/db`'s own ancestors (`/`, `/private`,
    /// `/private/var`) are root-owned and writable by nobody else, unlike
    /// `/var/run`, which is writable by the `daemon` group with no sticky
    /// bit and let a `gid=daemon` process redirect where the socket bound
    /// (review round 2).
    public static let defaultDaemonSocketPath = URL(fileURLWithPath: "/var/db/individuator-daemon/register.sock")
}
